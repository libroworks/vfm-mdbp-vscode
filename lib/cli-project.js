const fs = require("fs");
const path = require("path");
const { createHash } = require("crypto");
const { execFile } = require("child_process");

const CONFIG_NAME = "vivliostyle.config.js";
const EXISTS_MESSAGE = "vivliostyle.config.jsは既に存在します。再生成する場合は、既存ファイルを手動で削除してから、もう一度実行してください。";

function configSource(root, entry, runtime, output, workspace = ".vivliostyle", esm = false) {
  const source = `// Generated by MDBP. Edit entry to select chapters and their order.\n` +
    `const path = require("node:path");\n` +
    `const { createDocumentProcessor } = require(${JSON.stringify(runtime)});\n` +
    `const root = path.resolve(__dirname, ${JSON.stringify(root)});\n` +
    `module.exports = {\n  entryContext: root,\n  entry: ${JSON.stringify(entry)},\n` +
    `  workspaceDir: path.resolve(root, ${JSON.stringify(workspace)}),\n` +
    `  copyAsset: { includeFileExtensions: ["JPG", "JPEG", "PNG", "GIF", "SVG", "WEBP", "APNG"] },\n` +
    `  output: ${JSON.stringify(output)},\n  documentProcessor: createDocumentProcessor(root),\n};\n`;
  return esm ? `import { createRequire } from "node:module";\nimport { fileURLToPath } from "node:url";\n` +
    `const require = createRequire(import.meta.url);\n` + source.replace(
      'const root = path.resolve(__dirname,', 'const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),')
      .replace("module.exports =", "export default") : source;
}

function usesEsm(root) {
  let directory = path.resolve(root);
  while (true) {
    const packagePath = path.join(directory, "package.json");
    if (fs.existsSync(packagePath)) return JSON.parse(fs.readFileSync(packagePath, "utf8")).type === "module";
    const parent = path.dirname(directory);
    if (directory === parent) return false;
    directory = parent;
  }
}

function generateConfig(root, markdownPath, assetsDirectory) {
  const configPath = path.join(root, CONFIG_NAME);
  // Reserve first: EEXIST also covers a file created after the initial check.
  let descriptor;
  try { descriptor = fs.openSync(configPath, "wx"); }
  catch (error) {
    if (error.code === "EEXIST") throw new Error(EXISTS_MESSAGE);
    throw error;
  }
  try {
    const helper = path.join(root, ".mdbp-cli");
    fs.mkdirSync(helper, { recursive: true });
    for (const name of ["document-processor.cjs", "html-postprocess.cjs", "svgimg-transformer.cjs", "mermaid-transformer.cjs", "package.json"]) {
      fs.copyFileSync(path.join(assetsDirectory, name), path.join(helper, name));
    }
    const entry = path.relative(root, markdownPath).replace(/\\/g, "/");
    fs.writeFileSync(descriptor, configSource(".", [entry], "./.mdbp-cli/document-processor.cjs", "./output.pdf", ".vivliostyle", usesEsm(root)));
  } catch (error) {
    fs.closeSync(descriptor);
    fs.unlinkSync(configPath);
    throw error;
  }
  fs.closeSync(descriptor);
  return configPath;
}

function findConfigRoot(start, boundary) {
  let current = path.resolve(start);
  const limit = path.resolve(boundary);
  while (true) {
    if (fs.existsSync(path.join(current, CONFIG_NAME))) return current;
    if (current === limit || path.dirname(current) === current) break;
    const relative = path.relative(limit, current);
    if (relative.startsWith("..") || path.isAbsolute(relative)) break;
    current = path.dirname(current);
  }
  throw new Error("vivliostyle.config.jsが見つかりません。先に設定生成を実行してください。");
}

function currentFileConfig(root, filePath) {
  validateProject(root, true);
  const helper = path.join(root, ".mdbp-cli");
  const absolute = path.resolve(filePath);
  const identity = process.platform === "win32" ? absolute.toLowerCase() : absolute;
  const id = createHash("sha256").update(identity).digest("hex").slice(0, 24);
  const configPath = path.join(helper, `current-${id}.config.cjs`);
  const source = configSource("..", [path.relative(root, absolute).replace(/\\/g, "/")],
    "./document-processor.cjs", absolute.replace(/\.(md|html)$/i, ".pdf"), `.vivliostyle-current/${id}`);
  if (!fs.existsSync(configPath) || fs.readFileSync(configPath, "utf8") !== source) {
    fs.writeFileSync(configPath, source);
  }
  return configPath;
}

function validateProject(root, requireRuntime = false) {
  const config = path.join(root, CONFIG_NAME);
  if (!fs.existsSync(config) || !fs.statSync(config).isFile()) {
    throw new Error("vivliostyle.config.jsが見つかりません。先に設定生成を実行してください。");
  }
  const helper = path.join(root, ".mdbp-cli");
  if (!requireRuntime && !fs.existsSync(helper)) return false;
  for (const name of ["package.json", "document-processor.cjs", "html-postprocess.cjs", "svgimg-transformer.cjs"]) {
    const target = path.join(helper, name);
    if (!fs.existsSync(target) || !fs.statSync(target).isFile()) {
      throw new Error(`変換環境が不足しています: ${target}。先に設定生成を実行してください。`);
    }
  }
  return true;
}

function terminalCommand(command, shell, platform = process.platform) {
  return platform === "win32" && /powershell|pwsh/i.test(shell)
    ? command.replace(/^npm /, "npm.cmd ").replace(/^vivliostyle /, "vivliostyle.cmd ")
    : command;
}

async function exportHtml(root, markdownPath) {
  const helper = path.join(root, ".mdbp-cli");
  const cliPath = path.join(helper, "node_modules/@vivliostyle/cli/dist/cli.js");
  if (!fs.existsSync(cliPath) || !fs.existsSync(path.join(helper, "document-processor.cjs"))) {
    throw new Error('設定生成と npm install --prefix ".mdbp-cli" を先に実行してください。');
  }
  const temporary = fs.mkdtempSync(path.join(helper, "html-export-"));
  const workspace = path.join(temporary, "workspace");
  const configPath = path.join(temporary, "export.config.cjs");
  const htmlName = path.basename(markdownPath).replace(/\.md$/i, ".html");
  const htmlPath = markdownPath.replace(/\.md$/i, ".html");
  try {
    fs.writeFileSync(configPath, configSource("../..", [{
      path: path.relative(root, markdownPath).replace(/\\/g, "/"), output: htmlName,
    }], "../document-processor.cjs", path.join(temporary, "webpub"), workspace));
    await new Promise((resolve, reject) => {
      execFile("node", [cliPath, "build", "--config", configPath, "--format", "webpub", "--output", path.join(temporary, "webpub")],
        { cwd: root, windowsHide: true, maxBuffer: 4 * 1024 * 1024 }, (error, stdout, stderr) => {
          if (error) reject(new Error(`CLIによるHTML生成に失敗しました: ${stderr || stdout || error.message}`));
          else resolve();
        });
    });
    // Copy the processor output, before Web Publication packaging changes URLs.
    fs.copyFileSync(path.join(workspace, htmlName), htmlPath);
    return htmlPath;
  } finally {
    const relative = path.relative(helper, temporary);
    if (relative.startsWith("html-export-") && !relative.includes(path.sep)) {
      fs.rmSync(temporary, { recursive: true, force: true });
    }
  }
}

function installDependencies(root, onOutput = () => {}) {
  const helper = path.resolve(root, ".mdbp-cli");
  const manifest = path.join(helper, "package.json");
  if (!fs.existsSync(manifest)) {
    return Promise.reject(new Error(`インストール用のpackage.jsonが見つかりません: ${manifest}`));
  }
  return new Promise((resolve, reject) => {
    // .cmd cannot be executed by execFile directly; use cmd with fixed arguments.
    // Project paths are supplied as cwd, never interpolated into shell code.
    const windows = process.platform === "win32";
    const executable = windows ? "cmd.exe" : "npm";
    const args = windows ? ["/d", "/s", "/c", "npm.cmd install --prefix ."]
      : ["install", "--prefix", "."];
    onOutput(`インストール先: ${helper}\n`);
    const child = execFile(executable, args, { cwd: helper, windowsHide: true, maxBuffer: 8 * 1024 * 1024 },
      (error, stdout, stderr) => {
        if (error) reject(new Error(`依存パッケージのインストールに失敗しました（${helper}）: ${stderr || stdout || error.message}`));
        else resolve();
      });
    child.stdout?.on("data", onOutput);
    child.stderr?.on("data", onOutput);
  });
}

module.exports = { generateConfig, findConfigRoot, currentFileConfig, exportHtml, installDependencies, validateProject, terminalCommand, EXISTS_MESSAGE };
